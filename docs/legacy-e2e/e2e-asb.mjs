import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs'
import fs from 'fs'
const base = 'http://localhost:4173/'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const ctx = await browser.newContext({ viewport: { width: 1500, height: 950 }, acceptDownloads: true })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text()) })
const ok = (c, msg) => console.log((c ? 'PASS ' : 'FAIL ') + msg)
const setUser = async (id) => { await page.evaluate((id) => { const k='stroyai-demo-v1'; const s = JSON.parse(localStorage.getItem(k) || '{"state":{},"version":8}'); s.state.currentUserId = id; localStorage.setItem(k, JSON.stringify(s)) }, id); await page.reload(); await page.waitForTimeout(700) }
const money = (t) => Number(t.replace(/[^\d,]/g, '').replace(',', '.'))

await page.goto(base); await page.evaluate(() => localStorage.clear()); await setUser('u_pm2')
await page.goto(base + '#/cad?mode=dxf&project=p4'); await page.waitForTimeout(1200)
await page.getByRole('button', { name: 'Исполнительная схема' }).click(); await page.waitForTimeout(1200)
ok((await page.locator('[data-pt]').count()) === 12, 'точки пересечения осей найдены в DXF: 12')
ok(await page.getByTestId('scheme-preview').locator('svg').isVisible(), 'предпросмотр схемы')
ok(await page.getByRole('button', { name: 'Сохранить в ИД' }).isDisabled(), 'без съёмки сохранить нельзя')
await page.getByRole('button', { name: 'Демо-данные' }).click(); await page.waitForTimeout(300)
ok(await page.getByRole('button', { name: 'Сохранить в ИД' }).isDisabled() && await page.getByTestId('scheme-preview').getByText(/ДЕМО-ДАННЫЕ СЪЁМКИ/).isVisible(), 'демо-съёмку в ИД сохранить нельзя, схема помечена')
await page.getByLabel('Файл съёмки').setInputFiles({ name: 'semka.csv', mimeType: 'text/csv', buffer: Buffer.from('точка;dx;dy;dh\n1/А;3;-2;4\n2/А;12;1;\n3/Б;-2;5;15\nX/Z;1;1;1', 'utf8') }); await page.waitForTimeout(400)
ok(await page.getByText('Строка 5: точка «X/Z» не найдена на схеме').isVisible(), 'ошибки CSV показаны')
ok((await page.getByText(/Замерено точек:/).innerText()).includes('3 из 12') && (await page.getByText(/превышений:/).innerText()).includes('2'), 'по CSV: 3 точки, 2 превышения')
await page.getByLabel('1/Б dx').fill('4'); await page.waitForTimeout(150)
ok((await page.getByText(/Замерено точек:/).innerText()).includes('4 из 12'), 'ручной ввод добавляет точку')
await page.getByLabel('Допуск в плане').fill('15'); await page.waitForTimeout(150)
ok((await page.getByText(/превышений:/).innerText()).endsWith('1'), 'допуск 15 мм: остаётся 1 превышение (по высоте)')
await page.getByLabel('Допуск в плане').fill('8')
await page.screenshot({ path: '/tmp/asb1.png' })
let [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('dialog').getByRole('button', { name: 'DXF' }).click()])
const txt = new TextDecoder('windows-1251').decode(fs.readFileSync(await dl.path()))
ok(txt.includes('ИСП_ОТКЛ') && txt.includes('+12/+1'), 'схема в DXF с отклонениями')
await page.getByRole('button', { name: 'Сохранить в ИД' }).click(); await page.waitForTimeout(800)
ok(await page.getByTestId('doc-scheme').locator('svg').isVisible(), 'документ ИД с графической частью')
ok(await page.getByText(/Точка 2\/А: Δx \+12 мм, Δy \+1 мм — ПРЕВЫШЕНИЕ ДОПУСКА/).isVisible(), 'в тексте документа — таблица отклонений')
await page.screenshot({ path: '/tmp/asb2.png' })
console.log('ERRORS', errors.length, errors.slice(0, 5))
await browser.close()
