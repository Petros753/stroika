import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs'
import fs from 'fs'
const base = 'http://localhost:4173/'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const ctx = await browser.newContext({ viewport: { width: 1500, height: 950 }, acceptDownloads: true })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text()) })
const ok = (c, msg) => console.log((c ? 'PASS ' : 'FAIL ') + msg)

await page.goto(base); await page.evaluate(() => localStorage.clear())
await page.goto(base + '#/estimates?project=p2'); await page.waitForTimeout(800)
await page.reload(); await page.waitForTimeout(800)
await page.screenshot({ path: '/tmp/est0.png' })
ok(await page.getByText('Смета подрядчика').first().isVisible(), 'список смет содержит смету подрядчика')
await page.getByText('Смета подрядчика').first().click(); await page.waitForTimeout(400)
ok(await page.getByText('Разработка грунта экскаватором').first().isVisible(), 'просмотр сметы показывает позиции')
ok(await page.getByText('возможный дубль').first().isVisible(), 'в смете подрядчика помечены дубли')
await page.screenshot({ path: '/tmp/est1.png' })
let [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Выгрузить CSV' }).click()])
ok(dl.suggestedFilename().endsWith('.csv'), 'CSV сметы скачан: ' + dl.suggestedFilename())
await page.getByRole('button', { name: 'Закрыть', exact: true }).last().click()

await page.getByRole('button', { name: 'Сверка с ГРАНД-Сметой' }).click(); await page.waitForTimeout(500)
await page.screenshot({ path: '/tmp/est2.png', fullPage: true })
ok(await page.getByText('Разница B − A').isVisible(), 'KPI сверки видны')
ok(await page.getByText('Объём отличается').first().isVisible(), 'есть расхождения по объёму')
ok(await page.getByText('Нет в смете B').first().isVisible(), 'есть пропущенные позиции')
ok(await page.getByText(/Сопоставлено по наименованию/).first().isVisible(), 'нечёткое сопоставление по названию')
;[dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Отчёт CSV' }).click()])
const p = await dl.path(); const txt = fs.readFileSync(p, 'utf8')
ok(txt.includes('ИТОГО') && txt.split('\n').length > 30, 'отчёт CSV содержит строки и итог')
await page.getByRole('button', { name: 'Отчёт PDF' }).click()
ok(await page.getByText('Отчёт PDF (демо)').isVisible(), 'PDF — демо-окно')
await page.getByRole('button', { name: 'Понятно' }).click()

await page.getByRole('button', { name: 'Версии', exact: true }).click(); await page.waitForTimeout(400)
ok(await page.getByText('Версия A (старая)').isVisible(), 'вкладка версий')
await page.screenshot({ path: '/tmp/est3.png' })
await page.getByRole('button', { name: 'Отчёты' }).click(); await page.waitForTimeout(300)
ok((await page.getByRole('button', { name: 'Открыть сверку' }).count()) === 4, 'отчёты по 4 объектам')
await page.getByRole('button', { name: 'Открыть сверку' }).nth(2).click(); await page.waitForTimeout(400)
ok(await page.getByText('Разница B − A').isVisible(), 'переход из отчёта в сверку')

// загрузка CSV: директор не видит кнопку, сметчик видит
ok((await page.getByRole('button', { name: 'Загрузить смету' }).count()) === 0, 'директору загрузка сметы недоступна')
await page.evaluate(() => { localStorage.setItem('stroyai-demo-v1', JSON.stringify({ state: { currentUserId: 'u_est' }, version: 2 })) })
await page.reload(); await page.waitForTimeout(800)
await page.getByRole('button', { name: 'Загрузить смету' }).click()
fs.writeFileSync('/tmp/up.csv', '﻿Раздел;Шифр;Наименование;Ед.;Объём;Цена\r\nФундаменты;ФЕР06-01-001-05;Монолитная плита B25;м³;260;7900\r\nФундаменты;ФЕР06-01-004-02;Армирование;т;31;91000\r\n')
await page.locator('input[type=file]').setInputFiles('/tmp/up.csv'); await page.waitForTimeout(500)
ok(await page.getByText('Распознано позиций: 2').isVisible(), 'CSV распознан: 2 позиции')
await page.getByRole('button', { name: /Сохранить как v2/ }).click(); await page.waitForTimeout(500)
ok(await page.getByText('Монолитная плита B25').first().isVisible(), 'после загрузки открывается новая смета')
await page.screenshot({ path: '/tmp/est4.png' })

console.log(errors.length ? errors.join('\n') : 'no console errors')
await browser.close()
