import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs'
import fs from 'fs'
const base = 'http://localhost:4173/'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const ctx = await browser.newContext({ viewport: { width: 1500, height: 950 }, acceptDownloads: true })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text()) })
const ok = (c, msg) => console.log((c ? 'PASS ' : 'FAIL ') + msg)
const setUser = async (id) => { await page.evaluate((id) => { const k='stroyai-demo-v1'; const s = JSON.parse(localStorage.getItem(k) || '{"state":{},"version":2}'); s.state.currentUserId = id; localStorage.setItem(k, JSON.stringify(s)) }, id); await page.reload(); await page.waitForTimeout(700) }

await page.goto(base); await page.evaluate(() => localStorage.clear())
// ---- ПТО ----
await setUser('u_pto')
await page.goto(base + '#/pto?project=p2'); await page.waitForTimeout(700)
await page.getByRole('button', { name: /Требуется оформить/ }).click()
const missBefore = await page.getByRole('button', { name: 'Подготовить', exact: true }).count()
ok(missBefore > 0, 'есть требования к оформлению: ' + missBefore)
await page.getByRole('button', { name: 'Подготовить', exact: true }).first().click(); await page.waitForTimeout(300)
await page.getByRole('button', { name: 'Создать черновик' }).click(); await page.waitForTimeout(500)
ok(await page.getByText('ДЕМОНСТРАЦИОННЫЙ ШАБЛОН').first().isVisible(), 'в документе есть оговорка о демо-шаблоне')
await page.screenshot({ path: '/tmp/pto1.png' })
let [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Word' }).click()])
ok(dl.suggestedFilename().endsWith('.doc') && fs.readFileSync(await dl.path(), 'utf8').includes('ДЕМОНСТРАЦИОННЫЙ'), 'Word-файл скачан и содержит оговорку')
await page.getByRole('button', { name: 'Править' }).click()
await page.locator('textarea').fill((await page.locator('textarea').inputValue()) + '\nДополнено вручную')
await page.getByPlaceholder('Комментарий к версии').fill('тест')
await page.getByRole('button', { name: 'Сохранить версию' }).click(); await page.waitForTimeout(300)
ok(await page.getByText('Дополнено вручную').first().isVisible(), 'создана версия 2')
await page.getByRole('button', { name: 'На согласование' }).click(); await page.waitForTimeout(300)
ok(await page.getByText('На согласовании').first().isVisible(), 'статус: на согласовании')
ok((await page.getByRole('button', { name: 'Согласовать' }).count()) === 0, 'инженер ПТО не согласует сам')
await page.keyboard.press('Escape')
await setUser('u_pm2')
await page.goto(base + '#/pto?project=p2'); await page.waitForTimeout(600)
await page.locator('tbody tr', { hasText: 'На согласовании' }).first().click(); await page.waitForTimeout(300)
await page.getByRole('button', { name: 'Согласовать' }).click(); await page.waitForTimeout(300)
ok(await page.getByText('Согласован', { exact: true }).first().isVisible(), 'руководитель проекта согласовал')
await page.keyboard.press('Escape')
await page.getByRole('button', { name: /Требуется оформить/ }).click()
ok((await page.getByRole('button', { name: 'Подготовить', exact: true }).count()) === missBefore - 1, 'требований стало на 1 меньше')

// ---- Ассистент ----
await setUser('u_dir')
await page.goto(base + '#/assistant?ask=alerts'); await page.waitForTimeout(1200)
ok(await page.getByText(/Предупреждений: \d+/).first().isVisible(), 'ответ про предупреждения')
const alertsBefore = (await page.getByText(/Предупреждений: (\d+)/).first().textContent()).match(/Предупреждений: (\d+)/)[1]
await page.screenshot({ path: '/tmp/ass1.png' })
await page.getByPlaceholder(/Например/).fill('Какие объекты отстают от графика?'); await page.keyboard.press('Enter'); await page.waitForTimeout(900)
ok(await page.getByText(/От графика отстают объекты/).first().isVisible(), 'ответ про отставание')
await page.getByPlaceholder(/Например/).fill('Какой запас арматуры закладывать?'); await page.keyboard.press('Enter'); await page.waitForTimeout(900)
ok(await page.getByText(/Проверенное решение специалиста: Для плит/).first().isVisible(), 'KB: найдено проверенное решение')
// исправление
await page.getByRole('button', { name: 'Исправить' }).last().click()
await page.getByPlaceholder(/Как правильно/).fill('Тестовое решение про бетон В25 расход')
await page.getByRole('button', { name: 'Сохранить исправление' }).click(); await page.waitForTimeout(300)
ok(await page.getByText('Исправлено специалистом').first().isVisible(), 'исправление зафиксировано')
// после действия ответы меняются: согласуем заявку и спросим снова
await page.getByPlaceholder(/Например/).fill('Какие заявки ждут согласования?'); await page.keyboard.press('Enter'); await page.waitForTimeout(900)
const t1 = await page.getByText(/Активных заявок: \d+, из них на согласовании: \d+/).last().textContent()
await page.goto(base + '#/procurement'); await page.waitForTimeout(600)
await page.getByText('ЗК-0002').first().click(); await page.waitForTimeout(300)
await page.getByRole('button', { name: /Согласовать/ }).first().click(); await page.waitForTimeout(400)
await page.keyboard.press('Escape')
await page.goto(base + '#/assistant'); await page.waitForTimeout(600)
await page.getByPlaceholder(/Например/).fill('Какие заявки ждут согласования?'); await page.keyboard.press('Enter'); await page.waitForTimeout(900)
const t2 = await page.getByText(/Активных заявок: \d+, из них на согласовании: \d+/).last().textContent()
ok(t1 !== t2, `ответ изменился после действия: «${t1}» → «${t2}»`)

// ---- База знаний ----
await page.goto(base + '#/knowledge'); await page.waitForTimeout(600)
ok(await page.getByText('Тестовое решение про бетон').first().isVisible(), 'исправление попало в базу знаний')
await page.getByRole('button', { name: 'Добавить документ' }).click()
await page.getByPlaceholder(/СП 70/).fill('СП 70.13330 Несущие конструкции')
await page.getByRole('button', { name: 'Добавить', exact: true }).click(); await page.waitForTimeout(300)
ok(await page.getByText('СП 70.13330').first().isVisible(), 'документ добавлен')
await page.locator('tr', { hasText: 'СП 70.13330' }).getByRole('button', { name: 'Индексировать' }).click(); await page.waitForTimeout(200)
ok(await page.locator('tr', { hasText: 'СП 70.13330' }).getByText('в поиске').isVisible(), 'документ проиндексирован')
await page.screenshot({ path: '/tmp/kb1.png', fullPage: true })

// ---- Сотрудники ----
await setUser('u_admin')
await page.goto(base + '#/employees'); await page.waitForTimeout(600)
await page.screenshot({ path: '/tmp/emp1.png' })
const row = page.locator('tr', { hasText: 'Журавлёв' })
await row.getByRole('button', { name: 'Объекты' }).click()
await page.getByLabel(/Бизнес-центр/).uncheck()
await page.getByRole('button', { name: 'Сохранить' }).click(); await page.waitForTimeout(300)
await row.getByRole('button', { name: /Войти как/ }).click(); await page.waitForTimeout(600)
await page.goto(base + '#/projects'); await page.waitForTimeout(600)
ok(!(await page.getByText('Бизнес-центр «Атриум»').first().isVisible().catch(() => false)), 'прораб после снятия объекта его не видит')
await setUser('u_admin')
await page.goto(base + '#/employees'); await page.waitForTimeout(500)
await page.getByRole('button', { name: 'Матрица прав' }).click(); await page.waitForTimeout(200)
await page.screenshot({ path: '/tmp/emp2.png', fullPage: true })
ok(await page.getByText('Права на действия').isVisible(), 'матрица прав доступна')
console.log(errors.length ? errors.join('\n') : 'no console errors')
await browser.close()
