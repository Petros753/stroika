const r = (v: number, d = 0) => { const k = 10 ** d; return Math.round(v * k) / k }

function build(estId: string, items: Omit<EstimateItem, 'id'>[]): EstimateItem[] {
  return items.map((it, i) => ({ ...it, id: `${estId}_${String(i + 1).padStart(3, '0')}` }))
}

function baseItems(scale: number): Omit<EstimateItem, 'id'>[] {
  return CATALOG.map(([section, code, name, unit, qty, price]) => ({
    section, code, name, unit, qty: r(qty * scale, qty < 500 ? 1 : 0), price,
  }))
}

/** Версия 2 ГРАНД-Сметы: корректировка объёмов, индексация материалов, пара новых позиций */
function versionTwo(v1: Omit<EstimateItem, 'id'>[]): Omit<EstimateItem, 'id'>[] {
  const out = v1
    .map((it, i) => ({
      ...it,
      qty: i % 6 === 1 ? r(it.qty * 1.05, it.qty < 500 ? 1 : 0) : it.qty,
      price: i % 5 === 0 ? r(it.price * 1.04) : it.price,
    }))
  out.push({ section: 'Каркас и стены', code: 'ФЕР09-03-029-01', name: 'Монтаж металлоконструкций лестничных маршей', unit: 'т', qty: 38, price: 168000 })
  out.push({ section: 'Отделка', code: 'ФЕР15-06-001-01', name: 'Устройство подвесных потолков типа «Армстронг»', unit: 'м²', qty: 5400, price: 910 })
  return out
}

interface Profile { qtyBoost: number; priceBoost: number }

/** Смета подрядчика: те же работы с намеренными расхождениями */
function contractor(base: Omit<EstimateItem, 'id'>[], p: Profile): Omit<EstimateItem, 'id'>[] {
  const out: Omit<EstimateItem, 'id'>[] = []
  base.forEach((it, i) => {
    if (i === 6 || i === 17 || i === 30) return // пропущены позиции: гидроизоляция, окна, асфальт
    let { qty, price, name, code } = it
    if (i % 7 === 2) qty = r(qty * (1.08 + p.qtyBoost), qty < 500 ? 1 : 0)
    if (i % 9 === 4) price = r(price * (1.07 + p.priceBoost))
    if (i % 11 === 5) { qty = r(qty * 1.12, qty < 500 ? 1 : 0); price = r(price * 1.1) }
    if (i === 13) name = 'Теплоизоляция кровли минеральной ватой' // другое написание, тот же шифр
    if (i === 20) code = 'ТЕР15-01-015-01' // другой шифр, то же наименование — найдётся по названию
    out.push({ ...it, qty, price, name, code })
    if (i === 9) out.push({ ...it, qty, price, name: it.name }) // дубль армирования
    if (i === 22) out.push({ ...it, qty: r(it.qty * 0.04), name: it.name + ' (повторно)' }) // подозрительный дубль
  })
  out.push({ section: 'Каркас и стены', code: 'ФЕР09-03-029-01', name: 'Монтаж металлоконструкций лестничных маршей', unit: 'т', qty: 40, price: 175000 })
  out.push({ section: 'Благоустройство', code: 'ФЕР27-08-005-01', name: 'Устройство малых архитектурных форм', unit: 'шт', qty: 26, price: 48000 })
  out.push({ section: 'Сантехника и ОВ', code: 'ФЕР16-07-009-01', name: 'Пусконаладочные работы систем ОВиК', unit: 'компл', qty: 1, price: 2_450_000 })
  if (p.priceBoost > 0.05) out.push({ section: 'Отделка', code: 'ФЕР15-06-001-01', name: 'Устройство подвесных потолков типа «Армстронг»', unit: 'м²', qty: 5400, price: 1180 })
  return out
}

const TARGETS: { projectId: string; budget: number; profile: Profile }[] = [
  { projectId: 'p1', budget: 1_240_000_000, profile: { qtyBoost: 0, priceBoost: 0 } },
  { projectId: 'p2', budget: 640_000_000, profile: { qtyBoost: 0.02, priceBoost: 0.01 } },
  { projectId: 'p3', budget: 510_000_000, profile: { qtyBoost: 0.04, priceBoost: 0.06 } },
  { projectId: 'p4', budget: 920_000_000, profile: { qtyBoost: 0, priceBoost: 0.02 } },
]

const baseTotal = CATALOG.reduce((a, [, , , , q, p]) => a + q * p, 0)

function make(): Estimate[] {
  const res: Estimate[] = []
  for (const t of TARGETS) {
    const scale = (t.budget * 0.78) / baseTotal
    const v1 = baseItems(scale)
    const v2 = versionTwo(v1)
    const con = contractor(v2, t.profile)
    const g1 = `e_${t.projectId}_g1`, g2 = `e_${t.projectId}_g2`, c1 = `e_${t.projectId}_c1`
    res.push({ id: g1, projectId: t.projectId, name: 'Смета на СМР (основная)', version: 1, source: 'ГРАНД-Смета', date: '2025-05-20', items: build(g1, v1) })
    res.push({ id: g2, projectId: t.projectId, name: 'Смета на СМР (основная)', version: 2, source: 'ГРАНД-Смета', date: '2026-03-10', items: build(g2, v2) })
    res.push({ id: c1, projectId: t.projectId, name: 'Смета подрядчика', version: 1, source: 'Excel', date: '2026-09-02', items: build(c1, con) })
  }
  return res
}

export const seedEstimates: Estimate[] = make()
