export const qualityLine = (q: QualityDoc, materials: Material[]) =>
  `${q.kind} № ${q.number} от ${formatDate(q.issuedAt)} — ${materials.find((m) => m.id === q.materialId)?.name ?? q.materialId}${q.batch ? `, партия ${q.batch}` : ''} (${q.issuer})`

/** Заполнение шаблона по введённым пользователем данным. Детерминированно, без LLM. */
export function renderExecDocBody(opts: {
  kind: ExecDocKind
  project: Project
  stage?: Stage
  works: string[]
  date: string
  author: string
  note?: string
  attachments?: string[]
}): string {
  const { kind, project, stage, works, date, author, note, attachments } = opts
  const info = KIND_INFO[kind]
  const lines: string[] = []
  lines.push(DEMO_DISCLAIMER, '')
  lines.push(info.title.toUpperCase())
  lines.push(`№ ____ от ${formatDate(date)}`)
  lines.push('')
  lines.push(`Объект капитального строительства: ${project.name}`)
  lines.push(`Адрес: ${project.address}`)
  lines.push(`Застройщик / технический заказчик: ${project.customer}`)
  lines.push('Лицо, осуществляющее строительство: ________ (наименование, ОГРН, ИНН)')
  if (stage) {
    lines.push(`Этап: ${stage.name}`)
    lines.push(`Корпус / участок: ${stage.section}`)
    lines.push(`Вид работ: ${stage.workType}`)
  }
  lines.push('')
  if (kind === 'Журнал работ') {
    lines.push('Записи:')
    works.forEach((w, i) => lines.push(`  ${formatDate(date)} — ${w} (запись ${i + 1})`))
  } else {
    lines.push(kind === 'Реестр документации' ? 'Перечень документов:' : 'Предмет освидетельствования / испытания:')
    works.forEach((w, i) => lines.push(`  ${i + 1}. ${w}`))
  }
  const sec = info.sections({ stage })
  if (sec.length) { lines.push(''); sec.forEach((x) => lines.push(x)) }
  if (attachments && attachments.length) {
    lines.push('')
    lines.push('Приложения — документы о качестве применённых материалов:')
    attachments.forEach((a, i) => lines.push(`  ${i + 1}. ${a}`))
  }
  if (note) {
    lines.push('')
    lines.push(`Примечание: ${note}`)
  }
  lines.push('')
  lines.push(`Подготовил: ${author}`)
  lines.push('Представители: застройщика ________, лица, осуществляющего строительство ________, строительного контроля ________')
  return lines.join('\n')
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

/** HTML документа: открывается в Word (как .doc) и печатается в PDF. Оговорка о демо-шаблоне сохраняется в тексте. */
export function execDocHtml(title: string, version: number, body: string): string {
  return `<!DOCTYPE html><html lang="ru"><head><meta charset="utf-8"><title>${esc(title)}</title>
<style>body{font-family:'Times New Roman',serif;font-size:13pt;line-height:1.45;margin:2cm}
h1{font-size:15pt;text-align:center}pre{font-family:inherit;white-space:pre-wrap}
.demo{border:1px solid #b45309;color:#92400e;padding:6px 10px;font-size:10pt;margin-bottom:14px}</style></head>
<body><h1>${esc(title)} (версия ${version})</h1><pre>${esc(body)}</pre></body></html>`
}

/** Подсказки по составу работ для формы создания документа */
export function suggestWorks(kind: ExecDocKind, stage?: Stage): string[] {
  return KIND_INFO[kind].works(stage ? stage.workType : 'выполненные работы')
}
